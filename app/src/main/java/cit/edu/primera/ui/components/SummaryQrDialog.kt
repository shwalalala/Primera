@Composable
fun SummaryQrDialog(
    onDismissRequest: () -> Unit,
    onSavePdf: () -> Unit,
    onPrint: () -> Unit,
    onShare: () -> Unit,
    onRequestPdfUrl: (suspend () -> String?)? = null,
    qrContent: String = "PRIMERA HEALTH SUMMARY\nGenerated by Primera App",
    patientName: String? = null,
    modifier: Modifier = Modifier
) {
    var pdfUrl by remember { mutableStateOf<String?>(null) }
    var isUploading by remember { mutableStateOf(onRequestPdfUrl != null) }

    LaunchedEffect(onRequestPdfUrl) {
        if (onRequestPdfUrl != null) {
            isUploading = true
            val url = onRequestPdfUrl.invoke()
            pdfUrl = url
            isUploading = false
        }
    }

    val activeQrContent = pdfUrl ?: qrContent

    val qrBitmap = remember(activeQrContent) {
        DataExportHelper.generateQrCodeBitmap(
            content = activeQrContent,
            width = 512,
            height = 512,
            foregroundColor = android.graphics.Color.parseColor("#6A4C93"),
            backgroundColor = android.graphics.Color.WHITE
        )
    }

    Dialog(
        onDismissRequest = onDismissRequest,
        properties = DialogProperties(usePlatformDefaultWidth = false)
    ) {
        Surface(
            modifier = modifier
                .fillMaxWidth(0.92f)
                .clip(RoundedCornerShape(24.dp)),
            color = BackgroundCream
        ) {
            Column(
                modifier = Modifier
                    .fillMaxWidth()
                    .verticalScroll(rememberScrollState())
                    .padding(20.dp),
                horizontalAlignment = Alignment.CenterHorizontally
            ) {
                // Header Row
                Row(
                    modifier = Modifier.fillMaxWidth(),
                    horizontalArrangement = Arrangement.SpaceBetween,
                    verticalAlignment = Alignment.CenterVertically
                ) {
                    Row(
                        verticalAlignment = Alignment.CenterVertically,
                        horizontalArrangement = Arrangement.spacedBy(10.dp)
                    ) {
                        Box(
                            modifier = Modifier
                                .size(40.dp)
                                .clip(CircleShape)
                                .background(PrimeraLilac.copy(alpha = 0.4f)),
                            contentAlignment = Alignment.Center
                        ) {
                            Icon(
                                imageVector = Icons.Default.QrCode2,
                                contentDescription = "Summary QR",
                                tint = PrimeraViolet,
                                modifier = Modifier.size(24.dp)
                            )
                        }
                        Column {
                            Text(
                                text = "Health Summary QR",
                                fontSize = 18.sp,
                                fontWeight = FontWeight.Bold,
                                color = TextPrimary
                            )
                            if (!patientName.isNullOrBlank()) {
                                Text(
                                    text = patientName,
                                    fontSize = 12.sp,
                                    color = TextSecondary
                                )
                            }
                        }
                    }

                    IconButton(
                        onClick = onDismissRequest,
                        modifier = Modifier.size(32.dp)
                    ) {
                        Icon(
                            imageVector = Icons.Default.Close,
                            contentDescription = "Close",
                            tint = TextSecondary,
                            modifier = Modifier.size(20.dp)
                        )
                    }
                }

                Spacer(Modifier.height(16.dp))

                Text(
                    text = "Scan this QR code with any camera or phone scanner to open and download the Primera Health Summary PDF document.",
                    fontSize = 13.sp,
                    color = TextSecondary,
                    textAlign = TextAlign.Center,
                    lineHeight = 18.sp
                )

                Spacer(Modifier.height(16.dp))

                // QR Code Container Card
                Card(
                    modifier = Modifier
                        .fillMaxWidth()
                        .border(1.dp, MenuButtonBorder, RoundedCornerShape(20.dp)),
                    colors = CardDefaults.cardColors(containerColor = SurfaceWhite),
                    shape = RoundedCornerShape(20.dp)
                ) {
                    Column(
                        modifier = Modifier
                            .fillMaxWidth()
                            .padding(20.dp),
                        horizontalAlignment = Alignment.CenterHorizontally
                    ) {
                        Image(
                            bitmap = qrBitmap.asImageBitmap(),
                            contentDescription = "Automatically Generated Summary QR Code",
                            modifier = Modifier
                                .size(200.dp)
                                .clip(RoundedCornerShape(12.dp))
                        )

                        Spacer(Modifier.height(12.dp))

                        if (isUploading) {
                            Row(
                                verticalAlignment = Alignment.CenterVertically,
                                horizontalArrangement = Arrangement.spacedBy(6.dp),
                                modifier = Modifier
                                    .clip(RoundedCornerShape(16.dp))
                                    .background(PrimeraLilac.copy(alpha = 0.25f))
                                    .padding(horizontal = 12.dp, vertical = 6.dp)
                            ) {
                                CircularProgressIndicator(
                                    modifier = Modifier.size(14.dp),
                                    color = PrimeraViolet,
                                    strokeWidth = 2.dp
                                )
                                Text(
                                    text = "Generating Cloud PDF Link...",
                                    fontSize = 11.sp,
                                    fontWeight = FontWeight.SemiBold,
                                    color = PrimeraViolet
                                )
                            }
                        } else if (!pdfUrl.isNullOrBlank()) {
                            Row(
                                verticalAlignment = Alignment.CenterVertically,
                                horizontalArrangement = Arrangement.spacedBy(6.dp),
                                modifier = Modifier
                                    .clip(RoundedCornerShape(16.dp))
                                    .background(PrimeraLilac.copy(alpha = 0.25f))
                                    .padding(horizontal = 12.dp, vertical = 6.dp)
                            ) {
                                Icon(
                                    imageVector = Icons.Default.CheckCircle,
                                    contentDescription = null,
                                    tint = PrimeraViolet,
                                    modifier = Modifier.size(14.dp)
                                )
                                Text(
                                    text = "Direct PDF Link Ready • Scan to Save PDF",
                                    fontSize = 11.sp,
                                    fontWeight = FontWeight.SemiBold,
                                    color = PrimeraViolet
                                )
                            }
                        } else {
                            Row(
                                verticalAlignment = Alignment.CenterVertically,
                                horizontalArrangement = Arrangement.spacedBy(6.dp),
                                modifier = Modifier
                                    .clip(RoundedCornerShape(16.dp))
                                    .background(PrimeraLilac.copy(alpha = 0.25f))
                                    .padding(horizontal = 12.dp, vertical = 6.dp)
                            ) {
                                Icon(
                                    imageVector = Icons.Default.CheckCircle,
                                    contentDescription = null,
                                    tint = PrimeraViolet,
                                    modifier = Modifier.size(14.dp)
                                )
                                Text(
                                    text = "Auto-generated • Scan to Download",
                                    fontSize = 11.sp,
                                    fontWeight = FontWeight.SemiBold,
                                    color = PrimeraViolet
                                )
                            }
                        }
                    }
                }

                Spacer(Modifier.height(20.dp))

                // Options Section Header
                Row(
                    modifier = Modifier.fillMaxWidth(),
                    horizontalArrangement = Arrangement.Start
                ) {
                    Text(
                        text = "Summary Options",
                        fontSize = 15.sp,
                        fontWeight = FontWeight.Bold,
                        color = TextPrimary
                    )
                }

                Spacer(Modifier.height(10.dp))

                // Option 1: Save as PDF
                SummaryOptionCard(
                    icon = Icons.Default.PictureAsPdf,
                    title = "Save as PDF",
                    subtitle = "Save document directly to your device Downloads",
                    onClick = onSavePdf
                )

                Spacer(Modifier.height(8.dp))

                // Option 2: Print
                SummaryOptionCard(
                    icon = Icons.Default.Print,
                    title = "Print Summary",
                    subtitle = "Send directly to a connected printer",
                    onClick = onPrint
                )

                Spacer(Modifier.height(8.dp))

                // Option 3: Share
                SummaryOptionCard(
                    icon = Icons.Default.Share,
                    title = "Share Summary",
                    subtitle = "Share PDF via Email, Messaging, or Drive",
                    onClick = onShare
                )

                Spacer(Modifier.height(8.dp))

                // Option 4: Copy Link or Summary Text
                val context = LocalContext.current
                val clipboardManager = androidx.compose.ui.platform.LocalClipboardManager.current
                SummaryOptionCard(
                    icon = Icons.Default.ContentCopy,
                    title = if (!pdfUrl.isNullOrBlank()) "Copy PDF Link" else "Copy Summary Text",
                    subtitle = if (!pdfUrl.isNullOrBlank()) "Copy direct cloud PDF download link" else "Copy text summary to clipboard",
                    onClick = {
                        clipboardManager.setText(AnnotatedString(activeQrContent))
                        Toast.makeText(
                            context,
                            if (!pdfUrl.isNullOrBlank()) "PDF download link copied" else "Summary text copied",
                            Toast.LENGTH_SHORT
                        ).show()
                    }
                )

                Spacer(Modifier.height(20.dp))

                PrimeraOutlinedButton(
                    text = "Close",
                    onClick = onDismissRequest,
                    color = PrimeraViolet
                )
            }
        }
    }
}

@Composable
private fun SummaryOptionCard(
    icon: ImageVector,
    title: String,
    subtitle: String,
    onClick: () -> Unit,
    modifier: Modifier = Modifier
) {
    Row(
        modifier = modifier
            .fillMaxWidth()
            .clip(RoundedCornerShape(16.dp))
            .background(SurfaceWhite)
            .border(1.dp, MenuButtonBorder, RoundedCornerShape(16.dp))
            .clickable(onClick = onClick)
            .padding(14.dp),
        verticalAlignment = Alignment.CenterVertically
    ) {
        Box(
            modifier = Modifier
                .size(42.dp)
                .clip(CircleShape)
                .background(PrimeraLilac.copy(alpha = 0.35f)),
            contentAlignment = Alignment.Center
        ) {
            Icon(
                imageVector = icon,
                contentDescription = title,
                tint = PrimeraViolet,
                modifier = Modifier.size(22.dp)
            )
        }

        Spacer(Modifier.width(14.dp))

        Column(modifier = Modifier.weight(1f)) {
            Text(
                text = title,
                fontSize = 14.sp,
                fontWeight = FontWeight.Bold,
                color = TextPrimary
            )
            Spacer(Modifier.height(2.dp))
            Text(
                text = subtitle,
                fontSize = 11.sp,
                color = TextSecondary,
                lineHeight = 15.sp
            )
        }

        Icon(
            imageVector = Icons.AutoMirrored.Filled.KeyboardArrowRight,
            contentDescription = null,
            tint = TextSecondary,
            modifier = Modifier.size(20.dp)
        )
    }
}

